import { Kicker, Note } from './parts'

const TYPE_ROWS = [
  ['multiple_choice', 'Multiple choice'], ['short_answer', 'Short answer'], ['fill_blank', 'Fill in blank'],
  ['explain', 'Explain'], ['true_false', 'True / false'],
]
const PASS_PCT = 80
const ROW = { padding: '12px 0', borderTop: '1px solid var(--hairline)' }

function typeBreakdown(questions, scores) {
  return TYPE_ROWS.map(([type, label]) => {
    const idxs = questions.map((q, i) => (q.type === type ? i : -1)).filter(i => i >= 0)
    if (!idxs.length) return null
    return { label, correct: idxs.filter(i => scores[i] === 'got').length, total: idxs.length }
  }).filter(Boolean)
}

function ModelLine({ modelUsed, ollamaFallback }) {
  if (!modelUsed) return null
  const name = modelUsed === 'claude' ? 'Claude' : 'Llama 3.1'
  return (
    <span className="mono" style={{ fontSize: 11.5, color: 'var(--faint)' }}>
      Generated by {name}{ollamaFallback ? ' (Ollama offline)' : ''}
    </span>
  )
}

export default function Results({ results, modelUsed, ollamaFallback, mode, questions, scores, onRestart }) {
  const breakdown = mode === 'mixed' ? typeBreakdown(questions, scores) : []
  const stats = [
    { k: 'Score', v: `${results.pct}%`, accent: results.pct >= PASS_PCT },
    { k: 'Focus score', v: `${results.focusScore}%` },
    { k: 'XP earned', v: `+${results.xp}` },
    { k: 'Missed', v: results.missed, warn: results.missed > 0 },
  ]

  return (
    <section style={{ display: 'flex', flexDirection: 'column', gap: 36 }}>
      <header className="page-head" style={{ marginBottom: 0 }}>
        <span className="kicker">Quiz · Results</span>
        <h1 className="page-title">{results.correct} of {questions.length} correct</h1>
        <div style={{ marginTop: 8 }}><ModelLine modelUsed={modelUsed} ollamaFallback={ollamaFallback} /></div>
      </header>

      <div className="stat-row">
        {stats.map(s => (
          <div key={s.k}>
            <div className="v" style={{ color: s.accent ? 'var(--accent)' : s.warn ? 'var(--red)' : undefined }}>{s.v}</div>
            <div className="k">{s.k}</div>
          </div>
        ))}
      </div>

      {modelUsed === 'ollama' && <Note>Generated by Llama 3.1. Check important facts before your exam.</Note>}

      {breakdown.length > 0 && (
        <section>
          <Kicker>By question type</Kicker>
          {breakdown.map(r => (
            <div key={r.label} style={{ ...ROW, display: 'flex', justifyContent: 'space-between', fontSize: 14 }}>
              <span>{r.label}</span>
              <span className="mono" style={{ color: r.correct === r.total ? 'var(--accent)' : 'var(--muted)', fontSize: 13 }}>{r.correct}/{r.total}</span>
            </div>
          ))}
        </section>
      )}

      {results.weakTopics?.length > 0 && (
        <section>
          <Kicker>Weak topics</Kicker>
          {results.weakTopics.map((t, i) => (
            <div key={i} style={{ ...ROW, fontSize: 13.5, color: 'var(--muted)' }}>{t}</div>
          ))}
        </section>
      )}

      {results.missedQs.length > 0 && (
        <section>
          <Kicker>Missed · saved for spaced review</Kicker>
          {results.missedQs.map((q, i) => (
            <div key={i} style={ROW}>
              <div style={{ fontSize: 14, fontWeight: 500, lineHeight: 1.5 }}>{q.question}</div>
              <div style={{ fontSize: 13.5, color: 'var(--muted)', marginTop: 4, lineHeight: 1.55 }}>{q.answer}</div>
            </div>
          ))}
        </section>
      )}

      <div><button className="btn btn-accent" onClick={onRestart}>New quiz</button></div>
    </section>
  )
}
